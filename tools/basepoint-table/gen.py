#!/usr/bin/env python3
"""Write the doubling witnesses of DalekSim/BasepointTable.lean.

The proof of the basepoint table shows that entry 0 of row i + 1 is 2^8 times entry 0 of row
i. The check does not invert in the field. It checks eight doublings, with the denominators
multiplied out, through the points [2^k * 256^i] B, k = 0..8. The points are in affine
coordinates, as natural numbers below p. This script computes them. The Lean file checks every doubling, so this script is not trusted.

Usage: gen.py > shared/dalek/lean/DalekSim/BasepointTableData.lean
"""

P = 2**255 - 19
D = (-121665 * pow(121666, -1, P)) % P
BX = 15112221349535400772501151409588531511454012693041857206046113283949847762202
BY = 4 * pow(5, -1, P) % P


def add(p1, p2):
    (x1, y1), (x2, y2) = p1, p2
    t = D * x1 * x2 * y1 * y2
    return ((x1 * y2 + y1 * x2) * pow(1 + t, -1, P) % P,
            (y1 * y2 + x1 * x2) * pow(1 - t, -1, P) % P)


def main():
    assert (-BX * BX + BY * BY - 1 - D * BX * BX * BY * BY) % P == 0
    rows = []
    point = (BX, BY)
    for _ in range(31):
        chain = [point]
        for _ in range(8):
            chain.append(add(chain[-1], chain[-1]))
        point = chain[-1]
        rows.append("  [" + ",\n   ".join(f"({x}, {y})" for x, y in chain) + "]")
    print("""/-! Generated by `tools/basepoint-table/gen.py`. Do not edit.

The doubling witnesses of `DalekSim/BasepointTable.lean`: list `i` holds the points
`[2^k * 256^i] B` for `k = 0 .. 8`, in affine coordinates. -/

namespace DalekSim.BasepointTable

/-- The doubling witnesses: list `i` holds `[2^k * 256^i] B` for `k = 0 .. 8`. -/
def witnesses : List (List (Nat × Nat)) := [""")
    print(",\n".join(rows) + "]")
    print("\nend DalekSim.BasepointTable")


if __name__ == "__main__":
    main()
